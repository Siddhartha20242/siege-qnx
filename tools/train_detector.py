#!/usr/bin/env python3
"""Train the small convolutional detector that Siege's pipeline can run, and
write its weights to pipeline/model.h.

    python3 tools/train_detector.py            # needs numpy and torch; seeded, about a minute on a laptop

The task is the one the camera produces: find a bright 5x5 object in a noisy
32x32 greyscale frame. The network is deliberately tiny so that it runs in a
real-time budget:

    conv 3x3 (1->4) + ReLU -> conv 3x3 (4->4) + ReLU -> conv 1x1 (4->1)

Each valid 3x3 convolution trims one pixel from every edge, so the output is a
28x28 score map; the detection is its arg-max plus a 2 pixel offset. About
150 thousand multiply-adds per frame.

Training frames are made like the camera's (uniform noise, one object), with
extra variation so the network does not memorise the camera's exact noise:
brightness, noise level, and sometimes a dimmer distractor. It is then
checked on the camera's own frame sequence, regenerated bit for bit.
"""
import os, sys
import numpy as np
import torch
import torch.nn as nn

SEED = 20261106
torch.manual_seed(SEED)
rng = np.random.default_rng(SEED)
W = 32


def lcg_frames(n_frames):
    """The frames pipeline/frame_src.c produces, bit for bit, and the true object centres."""
    state = 0x5EED1234
    frames, gts = [], []
    for n in range(n_frames):
        f = np.empty(W * W, dtype=np.uint8)
        for i in range(W * W):
            state = (state * 1664525 + 1013904223) & 0xFFFFFFFF
            f[i] = (state >> 16) & 0x0F
        bx, by = 4 + (n * 1) % 24, 4 + (n * 2) % 24
        f = f.reshape(W, W)
        f[by - 2:by + 3, bx - 2:bx + 3] = 200
        frames.append(f)
        gts.append((bx, by))
    return np.stack(frames), np.array(gts)


def make_batch(n):
    noise_hi = rng.integers(10, 26, size=(n, 1, 1))
    x = (rng.random((n, W, W)) * noise_hi).astype(np.float32)
    gt = rng.integers(4, 28, size=(n, 2))
    level = rng.integers(140, 236, size=n)
    for i in range(n):
        bx, by = gt[i]
        if rng.random() < 0.3:                                  # a dimmer distractor, away from the object
            for _ in range(10):
                dx, dy = rng.integers(4, 28, size=2)
                if abs(dx - bx) > 6 or abs(dy - by) > 6:
                    x[i, dy - 2:dy + 3, dx - 2:dx + 3] = rng.integers(60, 110)
                    break
        x[i, by - 2:by + 3, bx - 2:bx + 3] = level[i]
    return torch.from_numpy(x / 255.0).unsqueeze(1), torch.from_numpy(gt)


def target_index(gt):
    return (gt[:, 1] - 2) * 28 + (gt[:, 0] - 2)               # score map is offset by 2 pixels


net = nn.Sequential(nn.Conv2d(1, 4, 3), nn.ReLU(), nn.Conv2d(4, 4, 3), nn.ReLU(), nn.Conv2d(4, 1, 1))
opt = torch.optim.Adam(net.parameters(), lr=3e-3)
sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=4000)
loss_fn = nn.CrossEntropyLoss()

for step in range(4000):
    x, gt = make_batch(128)
    loss = loss_fn(net(x).flatten(1), target_index(gt))
    opt.zero_grad(); loss.backward(); opt.step(); sched.step()
    if step % 500 == 0:
        print(f"step {step:4d} loss {loss.item():.4f}", flush=True)


def accuracy(x, gt):
    with torch.no_grad():
        idx = net(x).flatten(1).argmax(1)
    px, py = (idx % 28) + 2, (idx // 28) + 2
    dx, dy = (px - gt[:, 0]).abs(), (py - gt[:, 1]).abs()
    return (dx + dy == 0).float().mean().item(), ((dx <= 1) & (dy <= 1)).float().mean().item()


x, gt = make_batch(20000)
exact, within1 = accuracy(x, gt)
print(f"held-out random frames (20000): exact {exact:.4f}, within 1 px {within1:.4f}")

fr, g = lcg_frames(2400)                                      # 100 full cycles of the camera's path
exact_c, within1_c = accuracy(torch.from_numpy(fr.astype(np.float32) / 255.0).unsqueeze(1), torch.from_numpy(g))
print(f"the camera's own frames (2400):  exact {exact_c:.4f}, within 1 px {within1_c:.4f}")
if exact_c < 0.99:
    sys.exit("accuracy on the camera's frames is below 99%: not writing the model")

sd = {k: v.detach().numpy().astype(np.float32).ravel() for k, v in net.state_dict().items()}


def arr(name, a):
    return f"static const float {name}[{a.size}] = {{\n    " + ", ".join(f"{v:.9g}f" for v in a) + "\n};\n"


out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "pipeline", "model.h")
with open(out, "w") as f:
    f.write("/* Generated by tools/train_detector.py (seed %d). Do not edit.\n" % SEED)
    f.write(" * conv3x3 1->4, ReLU, conv3x3 4->4, ReLU, conv1x1 4->1; weights are [out][in][ky][kx].\n")
    f.write(" * Accuracy on the camera's frames: exact %.4f, within 1 px %.4f. */\n" % (exact_c, within1_c))
    f.write("#ifndef SIEGE_MODEL_H\n#define SIEGE_MODEL_H\n\n")
    f.write(arr("cnn_w1", sd["0.weight"]) + arr("cnn_b1", sd["0.bias"]))
    f.write(arr("cnn_w2", sd["2.weight"]) + arr("cnn_b2", sd["2.bias"]))
    f.write(arr("cnn_w3", sd["4.weight"]) + arr("cnn_b3", sd["4.bias"]))
    f.write("\n#endif\n")
print("wrote", os.path.normpath(out))
