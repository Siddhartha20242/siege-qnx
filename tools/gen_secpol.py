#!/usr/bin/env python3
"""Write the QNX security policies Siege can push into the kernel: image/secpol/*.secpol.

    python3 tools/gen_secpol.py

All five policies give every process of type `default` (the pipeline's camera and
controller, the shell, the harness) every ability, so they behave exactly as they
did before any policy. They differ only in what the *untrusted neighbour*
(type `atk_t`, the attacker programs) may do:

    open     nothing is restricted (control: a policy is loaded, behaviour is unchanged)
    connect  atk_t may not connect to the detector's channel (type `det_t`)
    ceiling  atk_t may connect, but may not raise its priority above 9, one below the pipeline
    names    atk_t may connect and run at any priority, but may not attach a name
             to the path space (so it cannot register the detector's service name)
    full     all three restrictions together

Compiled by scripts/build.sh with `secpolcompile -m` into build/secpol-<name>.bin,
pushed on the target with `secpolpush /proc/boot/secpol-<name>.bin` (image/pipeline.sh).
"""
import os

ABILITIES = ("spawn_setuid spawn_setgid setuid setgid getid pathspace reboot cpumode runstate confset rsrcdbmgr "
             "session umask event rlimit mem_add mem_phys mem_special mem_global mem_peer mem_lock spawn fork "
             "prot_exec wait msg_queue clockset dumper interrupt io trace priority connection schedule signal "
             "timer pgrp map_fixed path_trust swap rconstraint child_newapp public_channel aps_root able_create "
             "runstate_burst default_timer_tolerance xprocess_query chroot power prot_write_and_exec srandom "
             "rlimit_peer mac_policy xprocess_able xprocess_debug xprocess_mem_read high_resolution_timer "
             "untrusted_exec server_monitor sigev_thread privreg mountifs").split()
CEILING = 9      # strictly below the pipeline's priority 10: at 10 the attacker would be an equal, and equals still break it
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "image", "secpol")


def abilities(skip=(), extra=()):
    rows = ["    nonroot"] + [f"    {a}" for a in ABILITIES if a not in skip] + [f"    {e}" for e in extra]
    return "{\n" + "\n".join(rows) + "\n}"


def policy(name, connect=True, ceiling=False, names=True, det_drop=()):
    skip = set()
    extra = []
    if ceiling:
        skip.add("priority")
        extra.append(f"priority:1-{CEILING}")
    if not names:
        skip.add("pathspace")
    text = [f"# Siege security policy '{name}'. Generated by tools/gen_secpol.py; edit that, not this.", "",
            "type default;", "type det_t;     # the detector (and its supervisor): owner of the pipeline's service channel",
            "type atk_t;     # the untrusted neighbour: the attacker programs", "",
            "# The pipeline, the shell and the harness keep every ability, as before any policy.",
            f"allow default self:ability {abilities(extra=['settypeid:atk_t,det_t', 'gain_priv:channel_connect'])};",
            "allow_attach default /...;",
            f"allow det_t self:ability {abilities(det_drop)};",
            "allow_attach det_t /...;",
            "# The camera and controller (type default) send to the detector's channel.",
            "allow default det_t:channel connect;",
            "allow det_t default:channel connect;",
            "allow det_t det_t:channel connect;    # the supervisor checks the detector it started",
            "allow det_t atk_t:channel connect;    # the supervisor's owner check opens whatever holds the name",
            "allow atk_t atk_t:channel connect;", "",
            "# What the untrusted neighbour may do.",
            f"allow atk_t self:ability {abilities(skip, extra)};"]
    if names:
        text.append("allow_attach atk_t /...;")
    else:
        text.append("# no allow_attach for atk_t, and no pathspace ability: it cannot register a service name")
    text.append("allow atk_t det_t:channel connect;" if connect else
                "# no 'allow atk_t det_t:channel connect': it cannot send to the detector at all")
    return "\n".join(text) + "\n"


LEAST_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "det_least.txt")
PROBE_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "image", "secpol-probe")


def det_least():
    """The abilities det_t keeps in the `least` variant: tools/det_least.txt, written by tools/minimize_policy.py."""
    if not os.path.exists(LEAST_FILE):
        return None
    with open(LEAST_FILE) as f:
        return [w for w in f.read().split() if not w.startswith("#")]


VARIANTS = {
    "open":    dict(),
    "connect": dict(connect=False),
    "ceiling": dict(ceiling=True),
    "names":   dict(names=False),
    "full":    dict(connect=False, ceiling=True, names=False),
}

VARIANTS["bare"] = dict(det_drop=ABILITIES)     # control: det_t holds no ability at all. If the pipeline still runs, the probes prove nothing.
VARIANTS["minimal"] = dict(connect=False, ceiling=True, names=False, det_drop=ABILITIES)     # all three restrictions, det_t with no abilities
least = det_least()
if least is not None:
    VARIANTS["least"] = dict(connect=False, ceiling=True, names=False, det_drop=tuple(a for a in ABILITIES if a not in least))

if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for n, kw in VARIANTS.items():
        with open(os.path.join(OUT, n + ".secpol"), "w") as f:
            f.write(policy(n, **kw))
        print("wrote", os.path.normpath(os.path.join(OUT, n + ".secpol")))
