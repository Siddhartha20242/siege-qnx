#!/usr/bin/env python3
"""Write pipeline/scene.h (16 real-photo 32x32 backgrounds, brightest pixel 140) and pipeline/scene_hard.h
(32 backgrounds, brightest pixel 255, brighter than the object) for frame_src -s and -S.

    python3 tools/make_scene.py                  # needs numpy, Pillow, scikit-learn

Crops come from the right-hand 30% of china.jpg and flower.jpg (CC BY 2.0 by
Flickr users danielbuechele and vultilion, bundled with scikit-learn), scaled so
the brightest pixel is 140. The 5x5 object (200) is drawn over them at run time.
The detector's accuracy on such frames is checked by tools/eval_real_images.py.
"""
import os
import numpy as np
import sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from eval_real_images import photos, W



def write(name, cap, n, seed, sym, macro, header):
    rng = np.random.default_rng(seed)
    crops = []
    for i, (_, im) in enumerate(photos()):
        h, w = im.shape
        im = im / im.max() * cap
        for _ in range(n // 2):
            cx, cy = rng.integers(int(w * 0.7), w - W), rng.integers(0, h - W)
            crops.append(np.round(im[cy:cy + W, cx:cx + W]).astype(np.uint8))
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "pipeline", name)
    with open(out, "w") as f:
        f.write(header)
        f.write("#ifndef SIEGE_%s_H\n#define SIEGE_%s_H\n#define %s %d\n" % (macro, macro, macro + "_N", len(crops)))
        f.write("static const unsigned char %s[%s_N][%d] = {\n" % (sym, macro, W * W))
        for c in crops:
            f.write("  {" + ",".join(str(int(v)) for v in c.ravel()) + "},\n")
        f.write("};\n#endif\n")
    print("wrote", os.path.normpath(out))


CREDIT = ("/* Generated by tools/make_scene.py. Do not edit.\n"
          " * Crops of china.jpg and flower.jpg, Creative Commons BY 2.0 (Flickr: danielbuechele, vultilion). */\n")
write("scene.h", 140, 16, 20261107, "scene_px", "SCENE", CREDIT)
write("scene_hard.h", 255, 32, 20261109, "scene_hard_px", "SCENE_HARD", CREDIT)
